<?php

namespace App\Exports\Compensation;

use Maatwebsite\Excel\Concerns\FromCollection;
use Maatwebsite\Excel\Concerns\WithHeadings;
use Illuminate\Database\Eloquent\Collection;

class EntryExport implements FromCollection, WithHeadings
{
    protected Collection $entry;

    public function __construct(Collection $entry)
    {
        $this->entry = $entry;
    }

    public function collection()
    {
        return $this->entry->map(function ($unique_entry) {
            return [
                $unique_entry->entry_id,
                $unique_entry->branch_id,
                $unique_entry->branch_number,
                $unique_entry->amount,
                $unique_entry->vendor_no,
                $unique_entry->account_no,
                $unique_entry->description,
                $unique_entry->balance_type,
                $unique_entry->is_block_payment,
                $unique_entry->status,
                $unique_entry->generated_at,
                $unique_entry->generated_by,
                $unique_entry->posted_at,
                $unique_entry->posted_by,
            ];
        });
    }

    public function headings(): array
    {
        return [
            'Entry ID',
            'Branch',
            'Branch Number',
            'Amount',
            'Vendor No.',
            'Account No.',
            'Description',
            'Balance Type',
            'Block Payment',
            'Status',
            'Generated at',
            'Generated by',
            'Posted at',
            'Posted by'
        ];
    }
}
